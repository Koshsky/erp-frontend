/**
 * Centralized hint-content registry: every "?" explanation of the app lives
 * here (one place), rendered by the global HintPanel. Pages are plain
 * structured blocks (no raw HTML — CSP-safe, consistent styling).
 */

export type HintBlock =
  | { kind: 'p'; text: string }
  | { kind: 'ul' | 'ol'; items: string[] }
  | { kind: 'code'; text: string }

export interface HintPage {
  id: string
  title: string
  blocks: HintBlock[]
}

const pages = new Map<string, HintPage>()

/** Registers a hint page (a duplicate id is ignored). */
export function registerHint(page: HintPage): void {
  if (!page.id || pages.has(page.id)) return
  pages.set(page.id, page)
}

/** Returns a hint page by id (null — unknown). */
export function hintPage(id: string): HintPage | null {
  return pages.get(id) ?? null
}

/** All registered pages (for the stories/debug). */
export function hintPages(): HintPage[] {
  return [...pages.values()]
}

