import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const { webPolicy, securityHeaders } = createRequire(import.meta.url)('../desktop/security.cjs')
const lines = Object.entries({ ...securityHeaders(webPolicy), 'Strict-Transport-Security': 'max-age=31536000' })
  .map(([name, value]) => `add_header ${name} "${value}" always;`)
writeFileSync(new URL('../security-headers.conf', import.meta.url), `# Generated by node scripts/sync-csp.mjs; edit desktop/security.cjs instead.\n${lines.join('\n')}\n`)
